import AppKit
import Combine

/// A single recorded clipboard entry.
struct Clip: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var date: Date
    var appName: String?

    /// Single-line, length-limited title used in the menu bar.
    var menuTitle: String {
        let flat = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? ""
        let trimmed = flat.trimmingCharacters(in: .whitespaces)
        return trimmed.count > 40 ? String(trimmed.prefix(40)) + "…" : (trimmed.isEmpty ? "(whitespace)" : trimmed)
    }
}

/// Keys for settings persisted in UserDefaults.
enum SettingsKey {
    static let historySize = "historySize"
    static let skipDuplicates = "skipDuplicates"
    static let ignoredApps = "ignoredApps"
}

/// Owns the clipboard history: polls NSPasteboard, applies filters, and persists JSON atomically.
final class ClipStore: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    @Published var isPaused = false
    @Published var notice: String?

    static let maxHistory = 200
    private var timer: Timer?
    private var lastChangeCount: Int
    private let pasteboard = NSPasteboard.general
    private let fileURL: URL

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSTemporaryDirectory())
        let dir = support.appendingPathComponent("ClipMergeEditor", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")
        lastChangeCount = pasteboard.changeCount
        UserDefaults.standard.register(defaults: [SettingsKey.historySize: Self.maxHistory,
                                                  SettingsKey.skipDuplicates: true])
        load()
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    deinit { timer?.invalidate() }

    // MARK: Polling

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !isPaused else { return }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.skippedTypes.contains) else { return }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }

        let app = NSWorkspace.shared.frontmostApplication
        let ignored = ignoredApps
        if let name = app?.localizedName?.lowercased(), ignored.contains(name) { return }
        if let bundle = app?.bundleIdentifier?.lowercased(), ignored.contains(bundle) { return }
        add(text, appName: app?.localizedName)
    }

    private var ignoredApps: Set<String> {
        let raw = UserDefaults.standard.string(forKey: SettingsKey.ignoredApps) ?? ""
        return Set(raw.split(whereSeparator: { $0 == "\n" || $0 == "," })
            .map { $0.trimmingCharacters(in: .whitespaces).lowercased() }
            .filter { !$0.isEmpty })
    }

    // MARK: Mutations

    /// Adds text to the top of the history, honoring the duplicate and size settings.
    func add(_ text: String, appName: String?) {
        if UserDefaults.standard.bool(forKey: SettingsKey.skipDuplicates) {
            clips.removeAll { $0.text == text }
        }
        clips.insert(Clip(text: text, date: Date(), appName: appName), at: 0)
        enforceLimit()
        save()
    }

    func delete(_ ids: Set<UUID>) {
        clips.removeAll { ids.contains($0.id) }
        save()
    }

    func clearAll() {
        clips.removeAll()
        save()
    }

    func enforceLimit() {
        let stored = UserDefaults.standard.integer(forKey: SettingsKey.historySize)
        let limit = min(max(stored, 10), Self.maxHistory)
        if clips.count > limit { clips.removeLast(clips.count - limit) }
    }

    /// Writes text to the pasteboard and remembers the change count so it is not re-recorded.
    func copyToPasteboard(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: Persistence

    private func load() {
        guard FileManager.default.fileExists(atPath: fileURL.path) else { return }
        do {
            let data = try Data(contentsOf: fileURL)
            let decoder = JSONDecoder()
            decoder.dateDecodingStrategy = .iso8601
            clips = try decoder.decode([Clip].self, from: data)
            enforceLimit()
        } catch {
            let stamp = ISO8601DateFormatter().string(from: Date()).replacingOccurrences(of: ":", with: "-")
            let backup = fileURL.deletingLastPathComponent().appendingPathComponent("history-backup-\(stamp).json")
            try? FileManager.default.moveItem(at: fileURL, to: backup)
            clips = []
            notice = "The history file could not be read. It was backed up as \(backup.lastPathComponent) and a new, empty history was started."
        }
    }

    private func save() {
        do {
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            let data = try encoder.encode(clips)
            try data.write(to: fileURL, options: .atomic)
        } catch {
            notice = "Could not save history: \(error.localizedDescription)"
        }
    }
}
